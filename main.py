def draw_story(c, x, width, y, kicker, headline, body, head_scale=3):
    """One news block; returns the y just below it."""
    c.text(kicker, x, y, 2, RED)
    y += 14 + 6
    max_head = width // (6 * head_scale)
    for line in wrap(headline, max_head):
        c.text(line, x, y, head_scale, INK)
        y += 7 * head_scale + 6
    y += 2
    max_body = width // 12
    for line in wrap(body, max_body):
        c.text(line, x, y, 2, INK)
        y += 14 + 4
    return y


